const { chromium } = require('playwright');
const { mkdtemp, readFile, writeFile } = require('node:fs/promises');
const assert = require('node:assert/strict');
const { join, resolve } = require('node:path');
const { tmpdir } = require('node:os');
const { pathToFileURL } = require('node:url');

(async () => {
  const { startServer } = await import(pathToFileURL(resolve(__dirname, '../src/server.ts')).href);
  const directory = await mkdtemp(join(tmpdir(), 'perpops-ui-'));
  const app = await startServer({ mode: 'simulation', directory, port: 0 });
  const browser = await chromium.launch({ ...(process.env.PERPOPS_CHROMIUM ? { executablePath: process.env.PERPOPS_CHROMIUM } : {}), headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('favicon')) errors.push(message.text()); });
  const getState = async () => (await page.request.get(`${app.url}/api/state`)).json();
  const ready = async () => page.waitForFunction(() => !document.querySelector('#refresh-state').disabled && document.querySelector('#connection-state').textContent.includes('connected'));
  const waitStatus = async status => {
    await page.waitForFunction(expected => document.querySelector('#detail-status').textContent.toLowerCase() === expected, status);
    await ready();
  };
  const notes = [];
  try {
    await page.goto(app.url);
    await ready();
    assert.equal(await page.locator('#environment-label').textContent(), 'Local simulation');
    await page.screenshot({ path: join(directory, 'perpops-desktop-initial.png'), fullPage: true });

    await page.locator('#run-demo').click();
    await waitStatus('uncertain');
    let state = await getState();
    assert.equal(state.stats.transactionCount, 1);
    assert.equal(state.account.position, '0.001');
    const firstId = state.activeIntentId;
    await page.screenshot({ path: join(directory, 'perpops-desktop-uncertain.png'), fullPage: true });
    await page.locator('#recover-intent').click();
    await waitStatus('completed');
    state = await getState();
    assert.equal(state.stats.transactionCount, 1);
    assert.equal(state.account.position, '0.001');
    assert.equal(state.intents.find(intent => intent.id === firstId).status, 'completed');
    await page.locator('#retry-intent').click();
    await ready();
    state = await getState();
    assert.equal(state.stats.transactionCount, 1);
    assert.equal(state.account.position, '0.001');
    notes.push('Actual API recovery demo, reconciliation, and repeated same-ID request preserve one transaction and 0.001 BTC exposure.');

    const downloadEvent = page.waitForEvent('download');
    await page.locator('#export-receipt').click();
    const download = await downloadEvent;
    const downloadPath = join(directory, 'perpops-ui-receipt.json');
    await download.saveAs(downloadPath);
    const receiptText = await readFile(downloadPath, 'utf8');
    JSON.parse(receiptText);
    assert(!/rawTransaction|serializedTransaction|privateKey|signedRaw/i.test(receiptText));
    notes.push('Receipt downloads valid JSON without a serialized transaction or private key.');
    await ready();

    await page.locator('#close-position').click();
    assert.equal(await page.locator('#target-input').inputValue(), '0');
    assert(Number(await page.locator('#price-input').inputValue()) < 100000);
    await page.locator('#submit-intent').click();
    await waitStatus('completed');
    state = await getState();
    assert.equal(state.account.position, '0');
    assert.equal(state.stats.transactionCount, 2);
    assert.equal(state.stats.intentCount, 2);
    notes.push('Prepare close populates a zero target and a sell-side price; submitting it creates a separate completed intent.');

    await page.locator('label.fault-option').filter({ hasText: 'Fill part of the order' }).click();
    await page.locator('#arm-fault').click();
    await ready();
    await page.locator('[data-target="0.001"]').click();
    await page.locator('#submit-intent').click();
    await waitStatus('partial fill');
    state = await getState();
    assert.equal(state.account.position, '0.0005');
    assert.equal(state.stats.transactionCount, 3);
    await page.locator('#recover-intent').click();
    await waitStatus('completed');
    state = await getState();
    assert.equal(state.account.position, '0.001');
    assert.equal(state.stats.transactionCount, 4);
    notes.push('Partial fill is visible as 0.0005 BTC; resume fills only the 0.0005 remainder.');

    await page.locator('#close-position').click();
    await page.locator('#submit-intent').click();
    await waitStatus('completed');
    await page.locator('[data-target="0.001"]').click();
    await page.locator('#price-input').fill('1');
    await page.locator('#submit-intent').click();
    await waitStatus('paused');
    await page.locator('#cancel-intent').click();
    await waitStatus('cancelled');
    state = await getState();
    assert.equal(state.activeIntentId, null);
    assert.equal(state.account.position, '0');
    notes.push('An unmarketable limit pauses before submitting; Stop this intent cancels it and unlocks the composer.');

    await page.locator('label.fault-option').filter({ hasText: 'Return a stale read' }).click();
    await page.locator('#arm-fault').click();
    await ready();
    await page.locator('[data-target="0.001"]').click();
    await page.locator('#submit-intent').click();
    await ready();
    state = await getState();
    const staleId = state.activeIntentId;
    assert(staleId);
    const countBeforeRecovery = state.stats.transactionCount;
    await page.locator('#settle-simulation').click();
    await ready();
    await page.locator('#recover-intent').click();
    await waitStatus('completed');
    state = await getState();
    assert.equal(state.stats.transactionCount, countBeforeRecovery);
    notes.push('Stale-read delay can be released and the confirmed intent reconciled without an additional transaction.');

    await page.screenshot({ path: join(directory, 'perpops-desktop-complete.png'), fullPage: true });
    const desktopOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(desktopOverflow, false);
    await page.setViewportSize({ width: 375, height: 812 });
    await page.screenshot({ path: join(directory, 'perpops-mobile-complete.png'), fullPage: true });
    const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(mobileOverflow, false);
    await page.locator('#close-position').click();
    await page.locator('#submit-intent').click();
    await waitStatus('completed');
    state = await getState();
    assert.equal(state.account.position, '0');
    notes.push('Desktop 1440px and mobile 375px have no document-level horizontal overflow; mobile close workflow completes.');

    const countBeforeSendFailure = state.stats.transactionCount;
    await page.locator('label.fault-option').filter({ hasText: 'Fail before the exchange' }).click();
    await page.locator('#arm-fault').click();
    await ready();
    await page.locator('[data-target="0.001"]').click();
    await page.locator('#submit-intent').click();
    await waitStatus('uncertain');
    state = await getState();
    const droppedIntent = state.intents.find(intent => intent.id === state.activeIntentId);
    const savedHash = droppedIntent.attempts[0].hash;
    const savedNonce = droppedIntent.attempts[0].nonce;
    assert.equal(state.account.position, '0');
    assert.equal(state.stats.transactionCount, countBeforeSendFailure + 1);
    assert.equal(await page.locator('#rebroadcast-intent').isVisible(), true);
    await page.locator('#rebroadcast-intent').click();
    await waitStatus('completed');
    state = await getState();
    const resent = state.intents.find(intent => intent.id === droppedIntent.id);
    assert.equal(state.account.position, '0.001');
    assert.equal(state.stats.transactionCount, countBeforeSendFailure + 1);
    assert.equal(resent.attempts.length, 1);
    assert.equal(resent.attempts[0].hash, savedHash);
    assert.equal(resent.attempts[0].nonce, savedNonce);
    assert.equal(await page.locator('#rebroadcast-intent').isVisible(), false);
    notes.push('A failure before the exchange leaves zero exposure; explicit resend completes with the same saved hash and nonce and one prepared transaction.');

    assert.deepEqual(errors, []);
    notes.push('No browser JavaScript or console errors.');
    const report = { passed: true, notes, finalStats: state.stats, screenshots: [join(directory, 'perpops-desktop-initial.png'),join(directory, 'perpops-desktop-uncertain.png'),join(directory, 'perpops-desktop-complete.png'),join(directory, 'perpops-mobile-complete.png')] };
    await writeFile(join(directory, 'perpops-ui-report.json'), `${JSON.stringify(report, null, 2)}\n`);
    process.stdout.write(`${JSON.stringify({ ...report, directory }, null, 2)}\n`);
  } finally { await browser.close(); await app.close(); }
})().catch(error => { process.stderr.write(`${error instanceof Error ? error.message : 'Browser test failed.'}\n`); process.exitCode = 1; });
